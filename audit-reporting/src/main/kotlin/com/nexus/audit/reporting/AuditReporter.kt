package com.nexus.audit.reporting

import com.nexus.audit.core.types.*
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import java.io.File

/**
 * Renders an [AuditResult] into Markdown, JSON, and HTML and writes the
 * requested formats to disk.
 */
object AuditReporter {

    private val json = Json { prettyPrint = true; ignoreUnknownKeys = true }

    private val severityRank = mapOf(
        Severity.CRITICAL to 5, Severity.HIGH to 4, Severity.MEDIUM to 3,
        Severity.LOW to 2, Severity.INFO to 1
    )

    fun renderMarkdown(result: AuditResult, projectRoot: File? = null): String = buildString {
        val all = result.phaseResults.values.flatMap { it.findings }
            .sortedByDescending { severityRank[it.severity] ?: 0 }
        appendLine("# Nexus Production-Readiness Audit")
        appendLine()
        appendLine("Generated: ${result.timestamp}  |  Execution time: ${result.executionTime}")
        appendLine()
        val d = result.deploymentDecision
        appendLine("## Deployment Decision: **${d.recommendation}**")
        appendLine()
        appendLine("> ${d.reasoning}")
        appendLine()
        appendLine("- Launch Readiness Score: **${"%.2f".format(result.launchReadinessScore)}/10**")
        appendLine("- Startup Quality Score: **${"%.2f".format(result.startupQualityScore)}/10**")
        appendLine("- Estimated effort: ${d.estimatedEffort.developerDays} dev-days (${d.estimatedEffort.complexity})")
        appendLine()
        if (d.blockers.isNotEmpty()) {
            appendLine("### 🚫 Blockers (must fix)")
            d.blockers.forEach { appendLine("- $it") }
            appendLine()
        }
        if (d.highRiskSystems.isNotEmpty()) {
            appendLine("### ⚠️ High-risk systems")
            d.highRiskSystems.forEach { appendLine("- $it") }
            appendLine()
        }

        appendLine("## Phase Scores")
        appendLine()
        appendLine("| Phase | Name | Score |")
        appendLine("|---|---|---|")
        result.phaseScores.toSortedMap().forEach { (n, s) ->
            appendLine("| $n | ${s.phaseName} | ${"%.1f".format(s.score)} |")
        }
        appendLine()

        appendLine("## Findings by Phase")
        appendLine()
        result.phaseResults.toSortedMap().forEach { (n, pr) ->
            val name = result.phaseScores[n]?.phaseName ?: "Phase $n"
            appendLine("### Phase $n — $name")
            appendLine()
            if (pr.findings.isEmpty()) {
                appendLine("_No findings._")
            } else {
                pr.findings.sortedByDescending { severityRank[it.severity] ?: 0 }.forEach { f ->
                    appendLine("#### [${f.severity}] ${f.title}")
                    appendLine()
                    appendLine(f.description)
                    f.location?.let { loc ->
                        val path = displayLocation(loc, projectRoot)
                        appendLine("_Location: $path${loc.line?.let { ":$it" } ?: ""}_")
                    }
                    appendLine("**Fix:** ${f.recommendation}")
                    appendLine()
                }
            }
        }
        appendLine("---")
        appendLine("_${all.size} total findings. Generated by the Nexus audit system._")
    }

    fun renderJson(result: AuditResult): String = json.encodeToString(result)

    private fun displayLocation(loc: CodeLocation, projectRoot: File?): String =
        if (projectRoot == null) loc.file.name
        else runCatching { loc.file.relativeTo(projectRoot).path.replace('\\', '/') }
            .getOrDefault(loc.file.name)

    fun renderHtml(result: AuditResult, projectRoot: File? = null): String {
        val all = result.phaseResults.values.flatMap { it.findings }
            .sortedByDescending { severityRank[it.severity] ?: 0 }
        val badge = when (result.deploymentDecision.recommendation) {
            DeploymentRecommendation.READY -> "#2e7d32"
            DeploymentRecommendation.READY_WITH_RISKS -> "#f9a825"
            DeploymentRecommendation.NOT_READY -> "#c62828"
        }
        val rows = all.joinToString("\n") { f ->
            val sev = f.severity.name
            val location = f.location?.let { loc ->
                displayLocation(loc, projectRoot) + (loc.line?.let { ":$it" } ?: "")
            }.orEmpty()
            "<tr><td><span class='sev sev-$sev'>$sev</span></td><td>${esc(f.title)}</td>" +
                "<td>${esc(f.category)}</td><td>${esc(location)}</td><td>${esc(f.description)}</td>" +
                "<td>${esc(f.recommendation)}</td></tr>"
        }
        val phaseRows = result.phaseScores.toSortedMap().map { (n, s) ->
            "<tr><td>$n</td><td>${esc(s.phaseName)}</td><td>${"%.1f".format(s.score)}</td></tr>"
        }.joinToString("\n")
        return """
        <!doctype html><html><head><meta charset="utf-8"><title>Nexus Audit</title>
        <style>
        body{font-family:system-ui,Segoe UI,Arial;margin:2rem;color:#222}
        h1{margin-bottom:.2rem}.badge{display:inline-block;padding:.3rem .8rem;border-radius:6px;color:#fff;font-weight:700;background:$badge}
        table{border-collapse:collapse;width:100%;margin:1rem 0;font-size:14px}
        th,td{border:1px solid #ddd;padding:.5rem;text-align:left;vertical-align:top}
        th{background:#f5f5f5}
        .sev{padding:.1rem .4rem;border-radius:4px;color:#fff;font-size:12px}
        .sev-CRITICAL{background:#c62828}.sev-HIGH{background:#ef6c00}.sev-MEDIUM{background:#f9a825;color:#222}
        .sev-LOW{background:#1565c0}.sev-INFO{background:#607d8b}
        </style></head><body>
        <h1>Nexus Production-Readiness Audit</h1>
        <p><span class="badge">${result.deploymentDecision.recommendation}</span></p>
        <p>Launch Readiness <b>${"%.2f".format(result.launchReadinessScore)}/10</b> &nbsp; Startup Quality <b>${"%.2f".format(result.startupQualityScore)}/10</b></p>
        <h2>Phase Scores</h2><table><tr><th>#</th><th>Phase</th><th>Score</th></tr>$phaseRows</table>
        <h2>Findings (${all.size})</h2>
        <table><tr><th>Severity</th><th>Title</th><th>Category</th><th>Location</th><th>Description</th><th>Fix</th></tr>$rows</table>
        <p><i>Generated ${result.timestamp}</i></p>
        </body></html>
        """.trimIndent()
    }

    private fun esc(s: String): String = s
        .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        .replace("\"", "&quot;").replace("\n", " ")

    /** Writes the requested formats to [config.reportOutputDir] and returns the written files. */
    fun writeReports(config: AuditConfig, result: AuditResult): List<File> {
        val dir = config.reportOutputDir.apply { mkdirs() }
        val written = mutableListOf<File>()
        config.outputFormat.forEach { fmt ->
            val file = when (fmt) {
                OutputFormat.MARKDOWN -> File(dir, "audit-report.md").also {
                    it.writeText(renderMarkdown(result, config.projectRoot))
                }
                OutputFormat.JSON -> File(dir, "audit-report.json").also { it.writeText(renderJson(result)) }
                OutputFormat.HTML -> File(dir, "audit-report.html").also {
                    it.writeText(renderHtml(result, config.projectRoot))
                }
            }
            written.add(file)
        }
        return written
    }
}
